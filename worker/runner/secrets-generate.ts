import { fail } from '../lib/errors.ts';
import { fetchBounded, statusError, type Fetcher } from '../lib/fetch.ts';
import { isPlainObject, parseStrictJsonBytes } from '../lib/json.ts';
import { base64url, log } from '../lib/runtime.ts';

/**
 * `secrets.generate`: the root runner creates the state passphrases itself, so no human or
 * machine outside Cloudflare ever sees them. Create-only: an existing secret is never overwritten,
 * because replacing a state passphrase without an OpenTofu key migration makes the state
 * unreadable. Values are 32 bytes from `crypto.getRandomValues`, base64url; never logged or returned.
 *
 * VERIFY: request and response shapes of the Secrets Store API below
 * (`GET|POST /accounts/{account_id}/secrets_store/stores/{store_id}/secrets`), against
 * https://developers.cloudflare.com/api/resources/secrets_store/ before commissioning.
 */

/** The only names this job may create. */
export const GENERATED_SECRETS = ['TF_ENCRYPTION_ROOT', 'TF_ENCRYPTION_INFRA'] as const;
export type GeneratedSecret = (typeof GENERATED_SECRETS)[number];

export interface SecretsStoreDeps {
  fetcher: Fetcher;
  /** `CF_SECRETS_WRITE`: Secrets Store Write on this account only. */
  token(): Promise<string>;
  accountId: string;
  storeId: string;
  random(bytes: Uint8Array): Uint8Array;
}

export type EnsureOutcome = { name: GeneratedSecret; outcome: 'created' | 'exists' };

const API = 'https://api.cloudflare.com/client/v4';
const MAX_RESPONSE = 1024 * 1024;

function secretsUrl(deps: SecretsStoreDeps, query = ''): string {
  if (!/^[a-f0-9]{32}$/.test(deps.accountId) || !/^[a-f0-9]{32}$/.test(deps.storeId)) fail('secrets_store_unconfigured', 'account or store id is not configured');
  return `${API}/accounts/${deps.accountId}/secrets_store/stores/${deps.storeId}/secrets${query}`;
}

async function call(deps: SecretsStoreDeps, url: string, init: { method: string; body?: string }): Promise<unknown> {
  const token = await deps.token();
  const response = await fetchBounded(
    deps.fetcher,
    url,
    { method: init.method, headers: { authorization: `Bearer ${token}`, 'content-type': 'application/json' }, body: init.body, timeoutMs: 15_000, maxBytes: MAX_RESPONSE, redirect: 'manual' },
    'secrets_store',
  );
  if (response.status < 200 || response.status >= 300) throw statusError('secrets_store', `secrets store ${init.method}`, response.status);
  const body = parseStrictJsonBytes(response.bytes, MAX_RESPONSE, 'secrets_store');
  if (!isPlainObject(body) || body['success'] !== true) fail('secrets_store', 'secrets store reported failure');
  return body['result'];
}

/** Exact-name lookup (the API's `search` is a substring filter). */
async function exists(deps: SecretsStoreDeps, name: GeneratedSecret): Promise<boolean> {
  const result = await call(deps, secretsUrl(deps, `?search=${encodeURIComponent(name)}&per_page=100`), { method: 'GET' });
  if (!Array.isArray(result)) fail('secrets_store', 'secret list is malformed');
  return result.some((item) => isPlainObject(item) && item['name'] === name);
}

export async function ensureSecret(deps: SecretsStoreDeps, name: GeneratedSecret): Promise<EnsureOutcome> {
  if (!(GENERATED_SECRETS as readonly string[]).includes(name)) fail('secret_not_generatable', `${name} is not a generated secret`);
  if (await exists(deps, name)) return { name, outcome: 'exists' };
  const body = JSON.stringify([
    { name, value: base64url(deps.random(new Uint8Array(32))), scopes: ['workers'], comment: 'generated by root-runner secrets.generate; never rotate without a key migration' },
  ]);
  await call(deps, secretsUrl(deps), { method: 'POST', body });
  log('info', 'runner.secret_created', { name });
  return { name, outcome: 'created' };
}

export async function ensureGeneratedSecrets(deps: SecretsStoreDeps): Promise<EnsureOutcome[]> {
  const out: EnsureOutcome[] = [];
  for (const name of GENERATED_SECRETS) out.push(await ensureSecret(deps, name));
  return out;
}
